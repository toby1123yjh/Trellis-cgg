import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(scriptDir, "..");
const repositoryLicensePath = path.resolve(packageDir, "..", "..", "LICENSE");
const packageLicensePath = path.join(packageDir, "LICENSE");
const generatedMarkerPath = path.join(
  packageDir,
  ".trellis-ccg-lite-generated-license",
);

const action = process.argv[2];
const repositoryLicense = fs.readFileSync(repositoryLicensePath, "utf8");

if (action === "prepare") {
  if (fs.existsSync(packageLicensePath)) {
    const existingLicense = fs.readFileSync(packageLicensePath, "utf8");
    if (existingLicense !== repositoryLicense) {
      throw new Error(
        `Refusing to overwrite a different package license at ${packageLicensePath}`,
      );
    }
  } else {
    fs.writeFileSync(packageLicensePath, repositoryLicense, "utf8");
    fs.writeFileSync(generatedMarkerPath, "generated by prepack\n", "utf8");
  }
} else if (action === "cleanup") {
  if (!fs.existsSync(generatedMarkerPath)) {
    process.exit(0);
  }

  if (
    fs.existsSync(packageLicensePath) &&
    fs.readFileSync(packageLicensePath, "utf8") === repositoryLicense
  ) {
    fs.rmSync(packageLicensePath);
  } else if (fs.existsSync(packageLicensePath)) {
    console.warn(
      `Package license changed during packing; preserving ${packageLicensePath}`,
    );
  }

  fs.rmSync(generatedMarkerPath, { force: true });
} else {
  throw new Error(
    "Usage: node scripts/sync-package-license.js prepare|cleanup",
  );
}
